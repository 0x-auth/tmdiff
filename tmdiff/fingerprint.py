"""Stage 3: Structural fingerprinting & negation-aware tokenization."""
import hashlib
import re

NEGATIONS = {"not", "no", "never", "nahi", "na", "mat", "dont", "don't", "cannot", "can't", "!"}
BOILERPLATE_RE = re.compile(
    r"^(signed-off-by:|co-authored-by:|generated by|copyright\s+\d{4})",
    re.IGNORECASE,
)


def normalize_skeleton(text: str) -> str:
    """Strip variable literals (numbers, hex IDs, URLs, timestamps) to expose structural skeleton."""
    lines = [
        line.strip()
        for line in text.splitlines()
        if line.strip() and not BOILERPLATE_RE.match(line.strip())
    ]
    joined = " ".join(lines).lower()
    joined = re.sub(r"https?://\S+", "<URL>", joined)
    joined = re.sub(r"\b[0-9a-f]{8,}\b", "<HEX>", joined)
    joined = re.sub(r"\b\d+(\.\d+)?\b", "<NUM>", joined)
    joined = re.sub(r"\s+", " ", joined).strip()
    return joined


def structural_hash(text: str) -> str:
    skel = normalize_skeleton(text)
    return hashlib.sha256(skel.encode("utf-8")).hexdigest()[:16]


def tokenize(text: str) -> list[str]:
    """Tokenize content words while binding negation markers to the following term."""
    skel = normalize_skeleton(text)
    raw_tokens = re.findall(r"[a-z_<>]+", skel)
    out = []
    negate_next = False
    for tok in raw_tokens:
        if tok in NEGATIONS:
            negate_next = True
            continue
        if len(tok) < 2:
            continue
        if negate_next:
            out.append(f"¬{tok}")
            negate_next = False
        else:
            out.append(tok)
    return out
